# ==========================================================

# 1️⃣ O que são variáveis?
# Variáveis são apelidos que armazenam valores na memória do computador.
# Quando usamos o nome da variável, estamos acessando o valor guardado nela.

# 2️⃣ Operador de atribuição (=)
# O sinal de igual não significa comparação.
# Ele significa "recebe".
# O Python resolve primeiro o que está à direita
# e depois armazena o resultado na variável à esquerda.

# 3️⃣ Podemos armazenar:
# - Texto (str)
# - Número inteiro (int)
# - Número decimal (float)
# - Resultado de cálculos
# - Resultado de comparações (bool)

# 4️⃣ Expressões são resolvidas antes de serem salvas
# Se colocarmos uma conta em uma variável,
# o Python calcula primeiro e salva apenas o resultado final.

# 5️⃣ Variáveis evitam repetição de código
# Em vez de repetir o mesmo valor várias vezes,
# guardamos em uma variável e reutilizamos.
# Isso deixa o código mais organizado e fácil de manter.

# 6️⃣ Operadores de comparação
# São usados para fazer perguntas ao programa.
# Exemplos:
# maior que
# menor que
# maior ou igual
# menor ou igual

# O resultado de uma comparação é sempre:
# True  ou  False

# 7️⃣ Boolean (bool)
# Tipo de dado que representa verdadeiro ou falso.
# Muito usado para lógica no programa.

# 8️⃣ PEP 8 (guia de estilo)
# - Variáveis começam com letra minúscula.
# - Usamos snake_case para nomes compostos.
# - Nomes devem ser claros e descritivos.
# - Evitar nomes genéricos como x, y, a1.

# 9️⃣ Conclusão da aula
# Variáveis armazenam dados.
# Podemos guardar resultados de contas.
# Podemos guardar resultados de comparações.
# O código fica mais organizado e legível usando variáveis.
