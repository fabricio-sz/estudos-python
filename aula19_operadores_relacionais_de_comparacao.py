# ==========================================================
# AULA 19 — OPERADORES RELACIONAIS (DE COMPARAÇÃO)
# ==========================================================

# 1️⃣ O que são operadores relacionais?
# São operadores usados para comparar valores.
# O resultado de qualquer comparação é sempre um boolean:
# True  ou  False.

# 2️⃣ Operadores aprendidos:

# >   maior que
# >=  maior ou igual a
# <   menor que
# <=  menor ou igual a
# ==  igual a (comparação)
# !=  diferente de

# 3️⃣ Atenção importante:
# Um único = é atribuição (recebe).
# Dois == é comparação.

# 4️⃣ Como funciona cada um:

# >   verifica se o valor da esquerda é maior que o da direita.
# >=  verifica se é maior OU igual.
# <   verifica se é menor.
# <=  verifica se é menor OU igual.
# ==  verifica se os valores são iguais.
# !=  verifica se os valores são diferentes.

# 5️⃣ Resultado das comparações:
# Sempre retorna True ou False.
# Esse resultado pode ser armazenado em variáveis.

# 6️⃣ Uso comum:
# Geralmente usado com números.
# Muito utilizado dentro de estruturas if / elif / else.

# 7️⃣ Também funciona com outros tipos:
# Pode comparar strings.
# Comparação de strings considera caracteres (Unicode).
# Letras maiúsculas e minúsculas são diferentes.

# 8️⃣ Conceito importante:
# Comparar é diferente de atribuir.
# Comparação faz pergunta.
# Atribuição guarda valor.

# 9️⃣ Shell interativo:
# Permite testar comparações diretamente.
# Útil para testar expressões rapidamente sem usar print.

# 🔟 Conclusão:
# Operadores relacionais são base da lógica.
# São fundamentais para decisões no programa.
# Toda estrutura condicional depende deles.